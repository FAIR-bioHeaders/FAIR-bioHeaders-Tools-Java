package org.fairbioheaders;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.IOException;
import java.io.InputStream;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HexFormat;
import java.util.List;

import org.fairbioheaders.conformance.ConformanceHarness;
import org.junit.jupiter.api.Test;

import tools.jackson.databind.JsonNode;
import tools.jackson.databind.ObjectMapper;

/**
 * The default-behavior gate. The fingerprint of released-contract behavior captured from the
 * pre-refactor commit {@code 237da6c} is committed as
 * {@code src/test/resources/golden/default-behavior-v0.6.0.json} (192 799 bytes, SHA-256
 * {@code 2c7b2a02f6e3f4e8cd67c488895c0ce7d5761ac4a2f6185b754b2f92f083beaa}, recorded in
 * docs/STATUS.md). This test recomputes it and requires the same canonical bytes.
 *
 * <p>Why a golden and not only the unit tests: the registry refactor
 * (FAIR-bioHeaders-Tools-Java#4, issue #2 "five-type-extensible registry/API") changed how types
 * are declared, how the V1-V3 patterns are built and how the bundle resolves contracts, and the
 * claim under review is that none of that moved the default reading. The golden pins the release
 * registry, 304 selection outcomes, container inference, the verdict/issues/metadata of 47 header
 * documents, and all 228 embedded-header vector results, so drift - a changed message, a
 * reordered issue, a different contract behind a release - fails here with the first differing
 * line. The negative control run while writing this test (dropping {@code relatedLink[]} from the
 * R14 field table) moved the first difference to line 2091, which is what makes the positive
 * result worth reading. The golden is generated by the old code once and is never regenerated by
 * the code it constrains.
 *
 * <p>The vector part needs a FAIR-bioHeaders-Specification checkout; without one only the
 * checkout-free sections are compared and the receipt says {@code vectorsCompared=0} (the same
 * convention as {@link FileVectorTest}: missing fixtures are visible, never a pass). CI requires
 * the receipt to say 228.
 */
class DefaultBehaviorGoldenTest {

    private static final ObjectMapper JSON = new ObjectMapper();
    private static final String GOLDEN = "/golden/default-behavior-v0.6.0.json";
    private static final List<String> SECTIONS =
        List.of("fingerprintVersion", "configuration", "vectorsAvailable", "bundle", "selection",
            "kinds", "documents", "vectors");

    @Test
    void defaultBehaviorMatchesThePreRefactorGolden() {
        ConformanceHarness harness = new ConformanceHarness();
        boolean vectorsCompared = harness.vectorsAvailable();
        JsonNode actual = GoldenFingerprint.build(harness);
        byte[] actualBytes = GoldenFingerprint.toBytes(actual);
        byte[] expectedBytes = goldenBytes();

        JsonNode expected = JSON.readTree(new String(expectedBytes, StandardCharsets.UTF_8));
        List<String> differences = new ArrayList<>();
        for (String section : SECTIONS) {
            if (!vectorsCompared && (section.equals("vectors") || section.equals("vectorsAvailable"))) {
                // No specification checkout: the vector part is reported as not compared, by the
                // same convention as FileVectorTest (never a silent pass - CI asserts the receipt).
                continue;
            }
            JsonNode want = expected.get(section);
            JsonNode got = actual.get(section);
            if (want == null || got == null) {
                differences.add(section + ": missing section (golden=" + (want != null)
                    + " actual=" + (got != null) + ")");
                continue;
            }
            // Canonical bytes, not JsonNode.equals: the claim is that the rendered behavior is the
            // same text, and node-type equality (a decimal read back from an integer, say) is not
            // the thing under test.
            String wantText = new String(GoldenFingerprint.toBytes(want), StandardCharsets.UTF_8);
            String gotText = new String(GoldenFingerprint.toBytes(got), StandardCharsets.UTF_8);
            if (!wantText.equals(gotText)) {
                differences.add(firstTextualDifference(section, wantText, gotText));
            }
        }
        if (!differences.isEmpty()) {
            System.out.println("default-behavior fingerprint differs from the golden ("
                + actualBytes.length + " bytes now, sha256 " + sha256(actualBytes) + ")");
            differences.forEach(System.out::println);
        }
        assertTrue(differences.isEmpty(),
            () -> "default behavior changed against golden " + GOLDEN + ": " + differences.size()
                + " differing section(s), first: " + differences);

        // Positive controls on the fingerprint itself: a vacuous match must not read as a pass.
        assertTrue(actual.get("documents").size() >= 47,
            "the document battery should have run: " + actual.get("documents").size());
        assertTrue(actual.get("selection").size() >= 300,
            "the selection battery should have run: " + actual.get("selection").size());
        boolean anyValid = false;
        for (JsonNode doc : actual.get("documents")) {
            if ("VALID".equals(doc.get("status").asString())) {
                anyValid = true;
            }
        }
        assertTrue(anyValid, "at least one battery document must read VALID, or the valid-header"
            + " path is not covered here at all");
        if (vectorsCompared) {
            assertEquals(expected.get("vectors").size(), actual.get("vectors").size(),
                "every golden vector must be re-run");
            assertEquals(228, actual.get("vectors").size(), "the embedded-header vector count");
            long passed = 0;
            for (JsonNode vector : actual.get("vectors")) {
                if (vector.get("passed").asBoolean()) {
                    passed++;
                }
            }
            assertEquals(228, passed, "all embedded-header vectors must pass");
        }
        System.out.println("default-behavior golden verified: " + actualBytes.length + " bytes"
            + ", sha256 " + sha256(actualBytes) + ", golden sha256 " + sha256(expectedBytes)
            + ", vectors compared: " + (vectorsCompared ? "228" : "no specification checkout"));
        writeReport(actual, actualBytes, expectedBytes.length, vectorsCompared);
    }

    /**
     * A machine-readable receipt of what this test compared, so CI can require the vector part to
     * have run instead of trusting a green build that quietly skipped it. Written under
     * {@code -Dfh.report.dir} (default {@code target}), beside the surefire reports.
     */
    private static void writeReport(JsonNode actual, byte[] actualBytes, int goldenBytes,
                                boolean vectorsCompared) {
        Path dir = Path.of(System.getProperty("fh.report.dir", "target"));
        String text = "golden=" + GOLDEN + '\n'
            + "goldenBytes=" + goldenBytes + '\n'
            + "actualBytes=" + actualBytes.length + '\n'
            + "actualSha256=" + sha256(actualBytes) + '\n'
            + "vectorsCompared=" + (vectorsCompared ? 228 : 0) + '\n'
            + "documentsCompared=" + actual.get("documents").size() + '\n'
            + "selectionCasesCompared=" + actual.get("selection").size() + '\n'
            + "kindsCompared=" + actual.get("kinds").size() + '\n';
        try {
            Files.createDirectories(dir);
            Files.writeString(dir.resolve("default-behavior-golden.properties"), text);
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    /** The first line where two renderings of one section differ. */
    private static String firstTextualDifference(String section, String want, String got) {
        String[] wantLines = want.split("\n", -1);
        String[] gotLines = got.split("\n", -1);
        int n = Math.min(wantLines.length, gotLines.length);
        for (int i = 0; i < n; i++) {
            if (!wantLines[i].equals(gotLines[i])) {
                return section + " differs at line " + (i + 1) + " of " + wantLines.length + '\n'
                    + "  golden " + wantLines[i].strip() + '\n'
                    + "  actual " + gotLines[i].strip();
            }
        }
        return section + " differs in length: " + wantLines.length + " golden lines, "
            + gotLines.length + " actual";
    }

    private static byte[] goldenBytes() {
        try (InputStream in = DefaultBehaviorGoldenTest.class.getResourceAsStream(GOLDEN)) {
            if (in == null) {
                throw new IllegalStateException("missing golden resource " + GOLDEN
                    + " (generate it from commit 237da6c with GoldenDumpTest; see docs/STATUS.md)");
            }
            return in.readAllBytes();
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    private static String sha256(byte[] bytes) {
        try {
            return HexFormat.of().formatHex(
                java.security.MessageDigest.getInstance("SHA-256").digest(bytes));
        } catch (java.security.NoSuchAlgorithmException e) {
            throw new IllegalStateException(e);
        }
    }

    /** The golden is text, and it is the golden: its own digest is pinned here as well. */
    @Test
    void goldenIsThePinnedResource() {
        byte[] bytes = goldenBytes();
        String text = new String(bytes, StandardCharsets.UTF_8);
        assertFalse(text.indexOf('\r') >= 0, "the golden must use LF endings");
        assertTrue(text.contains("\"fingerprintVersion\": 1"), text.substring(0, 40));
        assertEquals(192_799, bytes.length, "the golden committed from 237da6c");
        assertEquals("2c7b2a02f6e3f4e8cd67c488895c0ce7d5761ac4a2f6185b754b2f92f083beaa",
            sha256(bytes), "the golden must not be regenerated to make a test pass");
    }
}
