package org.fairbioheaders;

import java.nio.file.Files;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.util.HexFormat;

import org.fairbioheaders.conformance.ConformanceHarness;
import org.junit.jupiter.api.Test;

/**
 * Writes the default-behavior fingerprint produced by the code on this checkout to the
 * path named by {@code -Dfh.golden.write=<file>}; does nothing otherwise. This is the
 * generator that captured the golden file once, from the pre-refactor commit
 * {@code 237da6c} (FAIR-bioHeaders-Tools-Java#4); the committed golden is never
 * regenerated by the code it constrains.
 *
 * <pre>
 * ./mvnw -B -ntp test -Dtest=GoldenDumpTest -DfailIfNoTests=true \
 *   -Dfh.golden.write=/tmp/default-behavior-v0.6.0.json \
 *   -Dfh.spec.dir=/path/to/FAIR-bioHeaders-Specification
 * </pre>
 */
class GoldenDumpTest {

    @Test
    void dumpWhenAsked() throws Exception {
        String target = System.getProperty("fh.golden.write");
        if (target == null || target.isBlank()) {
            return;
        }
        ConformanceHarness harness = new ConformanceHarness();
        byte[] bytes = GoldenFingerprint.toBytes(GoldenFingerprint.build(harness));
        Path path = Path.of(target);
        if (path.getParent() != null) {
            Files.createDirectories(path.getParent());
        }
        Files.write(path, bytes);
        String digest = HexFormat.of()
            .formatHex(MessageDigest.getInstance("SHA-256").digest(bytes));
        System.out.println("wrote " + bytes.length + " bytes of default-behavior fingerprint to "
            + path.toAbsolutePath() + " (sha256 " + digest + ", vectors="
            + harness.vectorsAvailable() + ")");
    }
}
