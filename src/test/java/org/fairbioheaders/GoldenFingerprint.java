    private static void add(ArrayNode out, BioHeaders verifier, String name, Kind kind, byte[] data) {
        VerifyResult result = verifier.verify(data, kind);
        ObjectNode entry = out.addObject();
        entry.put("name", name);
        entry.put("kind", kind.name());
        entry.put("status", result.status().name());
        entry.put("stated", result.statedChecksum());
        entry.put("computed", result.computedChecksum());
        JsonNode metadata = result.metadata();
        if (metadata == null) {
            entry.putNull("metadata");
        } else {
            entry.set("metadata", metadata);
        }
        entry.set("issues", issues(result.issues()));
    }

    // --------------------------------------------------------------- vectors

    private static void vectors(ObjectNode root, ConformanceHarness harness) {
        ArrayNode out = root.putArray("vectors");
        if (harness == null || !harness.vectorsAvailable()) {
            return;
        }
        for (JsonNode vector : harness.fileVectors()) {
            ConformanceHarness.Outcome outcome = null;
            try {
                outcome = harness.run(vector);
            } catch (IOException e) {
                throw new UncheckedIOException(e);
            }
            out.addObject().put("id", outcome.id())
                .put("format", outcome.format())
                .put("expected", outcome.expectedValid() ? "valid" : "invalid")
                .put("passed", outcome.passed())
                .put("status", String.valueOf(outcome.status()))
                .put("detail", outcome.detail());
        }
    }

    private static ArrayNode issues(List<Issue> list) {
        ArrayNode array = JSON.createArrayNode();
        for (Issue issue : list) {
            array.addObject().put("severity", issue.severity().name())
                .put("rule", issue.rule()).put("message", issue.message());
        }
        return array;
    }
