    private record Doc(String name, Kind kind, String text) {
    }

    /** Indent a YAML block as FASTA/GFA/GFF3 header lines of the given prefix. */
    private static String block(String prefix, String yaml) {
        StringBuilder sb = new StringBuilder();
        for (String line : yaml.split("\n", -1)) {
            if (line.isEmpty()) {
                continue;
            }
            sb.append(prefix).append(' ').append(line).append('\n');
        }
        return sb.toString();
    }

