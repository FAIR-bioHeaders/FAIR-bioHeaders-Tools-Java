    private static final List<String> VERSIONS =
        List.of("<absent>", "\"1\"", "1", "1.0", "true", "\"2.0\"", "2");

    private static void selection(ObjectNode root) {
        SchemaSelection selection = new SchemaSelection(SchemaBundle.getDefault());
        ArrayNode out = root.putArray("selection");
        for (String url : SCHEMA_URLS) {
            String quoted = url.replace("\\", "\\\\").replace("\"", "\\\"");
            out.addObject().put("section", "select").put("input", url)
                .put("outcome", select(selection, url));
            for (String version : VERSIONS) {
                String record = "{\"schema\":\"" + quoted + "\""
                    + (version.equals("<absent>") ? "" : ",\"schemaVersion\":" + version) + "}";
                out.addObject().put("section", "selectRecord").put("input", url).put("record", record)
                    .put("outcome", selectRecord(selection, JSON.readTree(record)));
            }
        }
    }

    private static String select(SchemaSelection selection, String url) {
        try {
            return describe(selection.select(url));
        } catch (SchemaSelection.Unsupported e) {
            return "V4: " + e.getMessage();
        }
    }

    private static String selectRecord(SchemaSelection selection, JsonNode record) {
        try {
            return describe(selection.selectRecord(record));
        } catch (SchemaSelection.Unsupported e) {
            return "V4: " + e.getMessage();
        }
    }

    private static String describe(SchemaSelection.Selection s) {
        Issue w = s.warning();
        return s.type().fileKey() + "@" + s.release()
            + (w == null ? " | none" : " | " + w.severity() + " " + w.rule() + ": " + w.message());
    }

    // ----------------------------------------------------------------- kinds

    private static void kinds(ObjectNode root) {
        ArrayNode out = root.putArray("kinds");
        for (String name : List.of("a.fa", "A.FA", "x.fasta", "x.fna", "x.fhr.fa", "x.fhp.fasta",
                "x.gfa", "x.GFA", "x.gff3", "x.gff3.gz", "x.fasta.gz", "x.fa.bgzip", "noext",
                "x.txt", "x.json", "x.fhgff3.gff3", "x.gfa.gz", "x.gz")) {
            out.addObject().put("name", name).put("kind", BioHeaders.kindFor(name).name());
        }
    }

